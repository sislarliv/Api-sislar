const catalogCodes = PERMISSION_CATALOG.map(([, code]) => code);

export const ALL_PERMISSIONS = [...new Set(catalogCodes)];

export function permissionsFor(profiles) {
  const set = new Set();
  for (const profile of profiles) {
    const granted = ROLE_PERMISSIONS[profile];
    if (!granted) continue;
    if (granted === "all") {
      for (const code of ALL_PERMISSIONS) set.add(code);
      continue;
    }
    for (const code of granted) set.add(code);
  }
  return set;
}
